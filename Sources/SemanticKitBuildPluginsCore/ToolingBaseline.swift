public enum ToolingBaseline {
    public static let packageName = "SemanticKitBuildPlugins"
    public static let commandVerb = "semantic-kit-build-plugins"
    public static let swiftToolsVersion = "6.3"
    public static let macOSDeploymentTarget = "26"
    public static let generatedFileHeader = "# Generated by SemanticKitBuildPlugins. Do not edit outside the CI/CD contract."

    public static let approvedDependencyURLs: Set<String> = [
        "https://github.com/jpsim/Yams.git",
        "https://github.com/open-policy-agent/swift-opa.git",
        "https://github.com/realm/SwiftLint.git",
    ]
}

public struct ValidationDiagnostic: Equatable, Sendable {
    public enum Severity: String, Sendable {
        case error
        case warning
        case note
    }

    public var severity: Severity
    public var message: String
    public var location: String?

    public init(severity: Severity, message: String, location: String? = nil) {
        self.severity = severity
        self.message = message
        self.location = location
    }
}

public struct ValidationReport: Equatable, Sendable {
    public var diagnostics: [ValidationDiagnostic]

    public init(diagnostics: [ValidationDiagnostic] = []) {
        self.diagnostics = diagnostics
    }

    public var hasErrors: Bool {
        diagnostics.contains { $0.severity == .error }
    }

    public mutating func append(_ diagnostic: ValidationDiagnostic) {
        diagnostics.append(diagnostic)
    }

    public mutating func append(contentsOf newDiagnostics: [ValidationDiagnostic]) {
        diagnostics.append(contentsOf: newDiagnostics)
    }
}
