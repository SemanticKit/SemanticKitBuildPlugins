import XCTest
@testable import SemanticKitBuildPluginsCommandSupport

final class CommandSupportTests: XCTestCase {
    func testInitDryRunDoesNotWriteFiles() throws {
        let directory = try temporaryDirectory()
        let result = try RepositoryInitializer().initialize(packageDirectory: directory, mode: .dryRun)

        XCTAssertEqual(result.exitCode, 0)
        XCTAssertTrue(result.messages.contains("DRY-RUN would write .github/workflows/ci.yml"))
        XCTAssertFalse(FileManager.default.fileExists(atPath: directory.appendingPathComponent(".github/workflows/ci.yml").path))
    }

    func testInitWriteIsDeterministic() throws {
        let directory = try temporaryDirectory()
        let initializer = RepositoryInitializer()

        _ = try initializer.initialize(packageDirectory: directory, mode: .write)
        let workflowURL = directory.appendingPathComponent(".github/workflows/ci.yml")
        let firstWorkflow = try String(contentsOf: workflowURL, encoding: .utf8)

        _ = try initializer.initialize(packageDirectory: directory, mode: .write)
        let secondWorkflow = try String(contentsOf: workflowURL, encoding: .utf8)

        XCTAssertEqual(firstWorkflow, secondWorkflow)
        XCTAssertTrue(firstWorkflow.contains("Generated by SemanticKitBuildPlugins"))
    }

    func testValidatePassesGeneratedFiles() async throws {
        let directory = try temporaryDirectory()
        _ = try RepositoryInitializer().initialize(packageDirectory: directory, mode: .write)

        let result = await RepositoryValidator().validate(packageDirectory: directory)
        XCTAssertEqual(result.exitCode, 0, result.diagnostics.map(\.message).joined(separator: "\n"))
    }

    func testCommandRunnerReportsMigrationProfiles() async throws {
        let directory = try temporaryDirectory()
        let result = await SemanticKitCommandRunner().run(
            context: ToolExecutionContext(arguments: ["migrate-scripts"], packageDirectory: directory)
        )

        XCTAssertEqual(result.exitCode, 0)
        XCTAssertTrue(result.messages.contains { $0.contains("sparql.conformance") })
        XCTAssertTrue(result.messages.contains { $0.contains("shacl.fast-conformance") })
    }

    private func temporaryDirectory() throws -> URL {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString, isDirectory: true)
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }
}
